// Builds dist/revid-subs.user.js by inlining the kit above the web shell.
//
// A userscript is one document with no module loader, so the kit is inlined
// as text rather than imported. It is read from ReVid's vendored copy so
// there is still exactly one source: fix a bug in the kit, re-vendor, rebuild,
// and the desktop app, the phone page and this script all move together.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const KIT = path.resolve(here, '../ReVid/electron/vendor/subtitle-overlay-kit.js');
const PARSER = path.join(here, 'src', 'vendor', 'bilingual-subtitle-kit.js');
const SHELL = path.join(here, 'src', 'overlay.js');
const OUT = path.join(here, 'dist', 'revid-subs.user.js');

// Each kit is inlined up to its export block: everything above it is plain
// function declarations, which is exactly what a userscript needs.
function inline(file, marker) {
    const src = fs.readFileSync(file, 'utf8');
    const cut = src.indexOf(marker);
    if (cut < 0) {
        throw new Error(`${path.basename(file)} has no "${marker}" — did the kit change shape?`);
    }
    return {
        body: src.slice(0, cut).replace(/^'use strict';\s*$/m, ''),
        commit: (src.match(/commit:\s+([0-9a-f]{7,40})/) || [])[1] || 'unknown'
    };
}

const overlay = inline(KIT, 'export {');
const parser = inline(PARSER, 'module.exports = {');
const commit = overlay.commit;
const kitBody = overlay.body + '\n' + parser.body;
const shell = fs.readFileSync(SHELL, 'utf8');

// The shell calls these by name. If a kit is re-vendored with a renamed or
// removed export, the bundle would still build and then throw in the page —
// so check here instead, where the message can say what is missing.
for (const name of ['visibleCue', 'cueProgress', 'fitInside', 'anchorToTop', 'clampTop',
    'dropAnchor', 'widthPctFrom', 'scaleFrom', 'parseSubtitles']) {
    if (!new RegExp(`function ${name}\\b`).test(kitBody)) {
        throw new Error(`the shell uses ${name}() but no inlined kit defines it`);
    }
}

const header = `// ==UserScript==
// @name         ReVid Subtitles
// @namespace    https://github.com/Jeffrey0117
// @version      0.1.0
// @description  把 ReVid 的字幕層蓋到網頁播放器上：長句自動切片、可拖曳、四角等比縮放、位置記住。
// @author       Jeffrey0117
// @match        *://*/*
// @grant        none
// @run-at       document-idle
// ==/UserScript==

/* Built by build.mjs — do not edit this file.
 *   shell: src/overlay.js
 *   kit:   subtitle-overlay-kit @ ${commit}
 *   kit:   bilingual-subtitle-kit @ ${parser.commit}
 */
`;

const bundle = '\n(function(){\n' + kitBody + '\n' + shell + '\n})();\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + bundle, 'utf8');

// The extension's content script is the same bundle without the userscript
// metadata block — one shell, two deliveries, so a fix cannot land in only
// one of them.
const EXT = path.join(here, 'extension', 'content.js');
fs.writeFileSync(EXT, `/* Built by build.mjs — do not edit.\n *   shell: src/overlay.js\n *   kit:   subtitle-overlay-kit @ ${commit}\n */\n` + bundle, 'utf8');

const kb = (f) => (fs.statSync(f).size / 1024).toFixed(1);
console.log(`built ${path.relative(here, OUT)} — ${kb(OUT)} KB`);
console.log(`built ${path.relative(here, EXT)} — ${kb(EXT)} KB`);
console.log(`kit @ ${commit.slice(0, 8)}`);
